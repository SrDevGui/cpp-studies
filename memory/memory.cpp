#include <iostream>
int main(){
  //memory address = a location in memory where data is stored
  //& = address of operator 
  //a memory address is a hexadecimal number that represents a location in memory
  std::string name = "Jhon";
  std::cout <<&name << "\n";
  bool s = true;
  std::cout <<&s << "\n";

  return 0;
}

